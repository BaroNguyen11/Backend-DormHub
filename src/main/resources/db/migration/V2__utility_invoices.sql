CREATE TABLE invoices (
    invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_type VARCHAR(32) NOT NULL,
    room_id BIGINT NOT NULL,
    billing_month DATE NOT NULL,
    issue_date TIMESTAMP(6) NOT NULL,
    total_amount NUMERIC(38, 0) NOT NULL,
    CONSTRAINT fk_invoices_room FOREIGN KEY (room_id) REFERENCES rooms (room_id),
    CONSTRAINT uk_invoices_room_month UNIQUE (room_id, billing_month),
    CONSTRAINT ck_invoices_utility_type CHECK (invoice_type = 'UTILITY'),
    CONSTRAINT ck_invoices_month_start CHECK (EXTRACT(DAY FROM billing_month) = 1),
    CONSTRAINT ck_invoices_total CHECK (total_amount >= 0)
);

CREATE TABLE invoice_details (
    detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL,
    item_type VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    quantity NUMERIC NOT NULL,
    unit_price NUMERIC NOT NULL,
    amount NUMERIC(38, 0) NOT NULL,
    CONSTRAINT fk_invoice_details_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (invoice_id),
    CONSTRAINT ck_invoice_details_item_type CHECK (item_type IN ('ELECTRICITY', 'WATER')),
    CONSTRAINT ck_invoice_details_quantity CHECK (quantity >= 0),
    CONSTRAINT ck_invoice_details_unit_price CHECK (unit_price > 0),
    CONSTRAINT ck_invoice_details_amount CHECK (amount >= 0)
);
