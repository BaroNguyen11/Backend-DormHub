CREATE TABLE rooms (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE prices (
    prices_id VARCHAR(255) PRIMARY KEY,
    type VARCHAR(255) NOT NULL,
    unit_price NUMERIC NOT NULL,
    effective_from DATE NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    created_by VARCHAR(255),
    note VARCHAR(255),
    CONSTRAINT uk_prices_type_effective_from UNIQUE (type, effective_from),
    CONSTRAINT ck_prices_type CHECK (type IN ('ELECTRICITY', 'WATER')),
    CONSTRAINT ck_prices_unit_price CHECK (unit_price > 0)
);

CREATE TABLE meter_readings (
    reading_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    reading_month DATE NOT NULL,
    electricity_old NUMERIC NOT NULL,
    electricity_new NUMERIC NOT NULL,
    water_old NUMERIC NOT NULL,
    water_new NUMERIC NOT NULL,
    electricity_price NUMERIC NOT NULL,
    water_price NUMERIC NOT NULL,
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_meter_readings_room FOREIGN KEY (room_id) REFERENCES rooms (room_id),
    CONSTRAINT uk_meter_readings_room_month UNIQUE (room_id, reading_month),
    CONSTRAINT ck_meter_readings_month_start CHECK (EXTRACT(DAY FROM reading_month) = 1),
    CONSTRAINT ck_meter_readings_electricity CHECK (electricity_old >= 0 AND electricity_new >= electricity_old),
    CONSTRAINT ck_meter_readings_water CHECK (water_old >= 0 AND water_new >= water_old),
    CONSTRAINT ck_meter_readings_prices CHECK (electricity_price > 0 AND water_price > 0),
    CONSTRAINT ck_meter_readings_status CHECK (status IN ('DRAFT', 'CONFIRMED'))
);
