CREATE TABLE contracts (
    contract_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    start_date TIMESTAMP(6) NOT NULL,
    end_date TIMESTAMP(6) NOT NULL,
    monthly_rent NUMERIC(38, 0) NOT NULL,
    status VARCHAR(32) NOT NULL,
    CONSTRAINT fk_contracts_room FOREIGN KEY (room_id) REFERENCES rooms (room_id),
    CONSTRAINT ck_contracts_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_contracts_rent CHECK (monthly_rent >= 0),
    CONSTRAINT ck_contracts_status CHECK (status IN ('PENDING', 'ACTIVE', 'EXPIRED', 'TERMINATED', 'CANCELLED'))
);

