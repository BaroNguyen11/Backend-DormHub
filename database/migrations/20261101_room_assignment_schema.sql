-- Building, room, application, and assignment tables aligned with main entities.
-- Apply after the base DormHub schema has created users, students, and rooms.
BEGIN;

CREATE TABLE IF NOT EXISTS public.buildings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(255),
    total_floors INTEGER NOT NULL,
    description TEXT,
    gender_restriction VARCHAR(20),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.buildings
    ADD COLUMN IF NOT EXISTS building_code VARCHAR(20),
    ADD COLUMN IF NOT EXISTS name VARCHAR(100),
    ADD COLUMN IF NOT EXISTS total_floors INTEGER,
    ADD COLUMN IF NOT EXISTS gender_restriction VARCHAR(20);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'buildings'
                 AND column_name = 'building_name') THEN
        EXECUTE 'UPDATE public.buildings SET name = building_name WHERE name IS NULL';
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'buildings'
                 AND column_name = 'gender_policy') THEN
        EXECUTE $sql$
            UPDATE public.buildings
            SET gender_restriction = CASE gender_policy::text
                WHEN 'MALE_ONLY' THEN 'MALE'
                WHEN 'FEMALE_ONLY' THEN 'FEMALE'
                ELSE gender_policy::text
            END
            WHERE gender_restriction IS NULL
        $sql$;
    END IF;
    IF EXISTS (SELECT 1 FROM public.buildings
               WHERE building_code IS NULL OR name IS NULL OR total_floors IS NULL) THEN
        RAISE EXCEPTION 'Cannot align buildings with the main Building entity: building_code, name, or total_floors is missing';
    END IF;
END $$;

UPDATE public.buildings
SET created_at = COALESCE(created_at, CURRENT_TIMESTAMP),
    updated_at = COALESCE(updated_at, created_at, CURRENT_TIMESTAMP);

ALTER TABLE public.buildings
    ALTER COLUMN building_code SET NOT NULL,
    ALTER COLUMN name SET NOT NULL,
    ALTER COLUMN total_floors SET NOT NULL,
    ALTER COLUMN created_at SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN created_at SET NOT NULL,
    ALTER COLUMN updated_at SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN updated_at SET NOT NULL;

-- Older schemas may retain these legacy columns. They are no longer mapped by
-- the main entities, so they must not block inserts that use the new columns.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'buildings'
                 AND column_name = 'building_name') THEN
        ALTER TABLE public.buildings ALTER COLUMN building_name DROP NOT NULL;
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'buildings'
                 AND column_name = 'gender_policy') THEN
        ALTER TABLE public.buildings ALTER COLUMN gender_policy DROP NOT NULL;
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'rooms'
                 AND column_name = 'price') THEN
        ALTER TABLE public.rooms ALTER COLUMN price DROP NOT NULL;
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uk_buildings_building_code
    ON public.buildings (building_code);

CREATE TABLE IF NOT EXISTS public.dorm_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    requested_room_id BIGINT NOT NULL,
    request_date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    note TEXT,
    review_note TEXT,
    processed_at TIMESTAMP WITHOUT TIME ZONE,
    processed_by BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_dorm_applications_student
        FOREIGN KEY (student_id) REFERENCES public.students (id),
    CONSTRAINT fk_dorm_applications_requested_room
        FOREIGN KEY (requested_room_id) REFERENCES public.rooms (id),
    CONSTRAINT fk_dorm_applications_processed_by
        FOREIGN KEY (processed_by) REFERENCES public.users (id)
);

ALTER TABLE public.dorm_applications
    ADD COLUMN IF NOT EXISTS processed_by BIGINT;

CREATE TABLE IF NOT EXISTS public.room_assignments (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    contract_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    assigned_by BIGINT NOT NULL,
    assigned_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    check_in_at TIMESTAMP WITHOUT TIME ZONE,
    check_out_at TIMESTAMP WITHOUT TIME ZONE,
    status VARCHAR(20) NOT NULL DEFAULT 'ASSIGNED',
    CONSTRAINT fk_room_assignments_student
        FOREIGN KEY (student_id) REFERENCES public.students (id),
    CONSTRAINT fk_room_assignments_room
        FOREIGN KEY (room_id) REFERENCES public.rooms (id),
    CONSTRAINT fk_room_assignments_assigned_by
        FOREIGN KEY (assigned_by) REFERENCES public.users (id)
);

-- Keep reruns compatible with a room_assignments table created by an earlier
-- feature revision before the main RoomAssignment shape was adopted.
ALTER TABLE public.room_assignments
    ADD COLUMN IF NOT EXISTS student_id BIGINT,
    ADD COLUMN IF NOT EXISTS contract_id BIGINT,
    ADD COLUMN IF NOT EXISTS assigned_by BIGINT,
    ADD COLUMN IF NOT EXISTS check_in_at TIMESTAMP WITHOUT TIME ZONE,
    ADD COLUMN IF NOT EXISTS check_out_at TIMESTAMP WITHOUT TIME ZONE;

ALTER TABLE public.rooms
    ADD COLUMN IF NOT EXISTS reserved_occupancy INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS price_per_month NUMERIC(10, 2),
    ADD COLUMN IF NOT EXISTS electric_meter_number VARCHAR(50),
    ADD COLUMN IF NOT EXISTS water_meter_number VARCHAR(50);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'rooms' AND column_name = 'price') THEN
        EXECUTE 'UPDATE public.rooms SET price_per_month = price WHERE price_per_month IS NULL';
    END IF;
    IF EXISTS (SELECT 1 FROM public.rooms
               WHERE status::text NOT IN ('AVAILABLE', 'OCCUPIED', 'FULL', 'MAINTENANCE', 'RESERVED')) THEN
        RAISE EXCEPTION 'Cannot align rooms with the main RoomStatus enum: unsupported status value exists';
    END IF;
    IF EXISTS (SELECT 1 FROM public.rooms
               WHERE room_number IS NOT NULL AND char_length(room_number) > 20) THEN
        RAISE EXCEPTION 'Cannot align rooms: room_number exceeds the main entity limit of 20 characters';
    END IF;
    IF EXISTS (SELECT 1 FROM public.rooms
               WHERE room_type IS NOT NULL AND char_length(room_type::text) > 20) THEN
        RAISE EXCEPTION 'Cannot align rooms: room_type exceeds the main entity limit of 20 characters';
    END IF;
    IF EXISTS (SELECT 1 FROM public.rooms WHERE price_per_month IS NULL) THEN
        RAISE EXCEPTION 'Cannot align rooms with the main Room entity: price_per_month cannot be inferred';
    END IF;
END $$;

ALTER TABLE public.rooms
    ALTER COLUMN room_number TYPE VARCHAR(20) USING room_number::text,
    ALTER COLUMN room_type TYPE VARCHAR(20) USING room_type::text,
    ALTER COLUMN price_per_month TYPE NUMERIC(10, 2) USING price_per_month::numeric(10, 2),
    ALTER COLUMN status DROP DEFAULT,
    ALTER COLUMN status TYPE VARCHAR(20) USING CASE status::text
        WHEN 'FULL' THEN 'OCCUPIED'
        ELSE status::text
    END,
    ALTER COLUMN status SET DEFAULT 'AVAILABLE';

ALTER TABLE public.rooms
    ALTER COLUMN created_at SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN updated_at SET DEFAULT CURRENT_TIMESTAMP;

UPDATE public.rooms
SET created_at = COALESCE(created_at, CURRENT_TIMESTAMP),
    updated_at = COALESCE(updated_at, created_at, CURRENT_TIMESTAMP);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.rooms
               WHERE building_id IS NULL OR room_number IS NULL OR floor IS NULL
                  OR capacity IS NULL OR current_occupancy IS NULL OR room_type IS NULL
                  OR price_per_month IS NULL
                  OR status IS NULL) THEN
        RAISE EXCEPTION 'Cannot align rooms with the Room entity: required fields contain NULL values';
    END IF;
END $$;

ALTER TABLE public.rooms
    ALTER COLUMN building_id SET NOT NULL,
    ALTER COLUMN room_number SET NOT NULL,
    ALTER COLUMN floor SET NOT NULL,
    ALTER COLUMN capacity SET NOT NULL,
    ALTER COLUMN current_occupancy SET NOT NULL,
    ALTER COLUMN reserved_occupancy SET NOT NULL,
    ALTER COLUMN room_type SET NOT NULL,
    ALTER COLUMN price_per_month SET NOT NULL,
    ALTER COLUMN status SET NOT NULL,
    ALTER COLUMN created_at SET NOT NULL,
    ALTER COLUMN updated_at SET NOT NULL;

CREATE INDEX IF NOT EXISTS idx_dorm_applications_student
    ON public.dorm_applications (student_id);
CREATE INDEX IF NOT EXISTS idx_dorm_applications_status
    ON public.dorm_applications (status);
CREATE INDEX IF NOT EXISTS idx_room_assignments_room_status
    ON public.room_assignments (room_id, status);
CREATE INDEX IF NOT EXISTS idx_room_assignments_student_status
    ON public.room_assignments (student_id, status);
CREATE INDEX IF NOT EXISTS idx_room_assignments_contract
    ON public.room_assignments (contract_id);

COMMIT;
