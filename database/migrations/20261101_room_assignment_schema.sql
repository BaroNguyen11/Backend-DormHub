-- Scoped schema update for Building, DormApplication, and RoomAssignment.
-- This is a manual migration draft; it is not executed automatically.
-- Existing room_status and rooms.current_occupancy are already present in PostgreSQL.

BEGIN;

ALTER TABLE public.buildings
    ADD COLUMN IF NOT EXISTS gender_policy VARCHAR(20);

CREATE TABLE IF NOT EXISTS public.dorm_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    requested_room_id BIGINT NOT NULL,
    request_date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    note TEXT,
    review_note TEXT,
    processed_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_dorm_applications_student
        FOREIGN KEY (student_id) REFERENCES public.students (id),
    CONSTRAINT fk_dorm_applications_requested_room
        FOREIGN KEY (requested_room_id) REFERENCES public.rooms (id)
);

CREATE INDEX IF NOT EXISTS idx_dorm_applications_student
    ON public.dorm_applications (student_id);
CREATE INDEX IF NOT EXISTS idx_dorm_applications_status
    ON public.dorm_applications (status);

CREATE TABLE IF NOT EXISTS public.room_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dorm_application_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ASSIGNED',
    assigned_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    note TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_room_assignments_application
        FOREIGN KEY (dorm_application_id) REFERENCES public.dorm_applications (id),
    CONSTRAINT fk_room_assignments_room
        FOREIGN KEY (room_id) REFERENCES public.rooms (id)
);

CREATE INDEX IF NOT EXISTS idx_room_assignments_room_status
    ON public.room_assignments (room_id, status);
CREATE INDEX IF NOT EXISTS idx_room_assignments_application
    ON public.room_assignments (dorm_application_id);

COMMIT;
