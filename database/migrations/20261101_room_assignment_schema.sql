-- Building, room, application, and assignment tables aligned with main entities.
-- Apply after the base DormHub schema has created users, students, and rooms.
BEGIN;

CREATE TABLE IF NOT EXISTS public.buildings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_name VARCHAR(100) NOT NULL,
    address VARCHAR(255),
    description TEXT,
    gender_policy VARCHAR(20),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.buildings
    ADD COLUMN IF NOT EXISTS gender_policy VARCHAR(20);

CREATE TABLE IF NOT EXISTS public.dorm_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    requested_room_id BIGINT NOT NULL,
    request_date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    note TEXT,
    review_note TEXT,
    processed_at TIMESTAMP WITHOUT TIME ZONE,
    processed_by BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_dorm_applications_student
        FOREIGN KEY (student_id) REFERENCES public.students (id),
    CONSTRAINT fk_dorm_applications_requested_room
        FOREIGN KEY (requested_room_id) REFERENCES public.rooms (id),
    CONSTRAINT fk_dorm_applications_processed_by
        FOREIGN KEY (processed_by) REFERENCES public.users (id)
);

ALTER TABLE public.dorm_applications
    ADD COLUMN IF NOT EXISTS processed_by BIGINT;

CREATE TABLE IF NOT EXISTS public.room_assignments (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    contract_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    assigned_by BIGINT NOT NULL,
    assigned_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    check_in_at TIMESTAMP WITHOUT TIME ZONE,
    check_out_at TIMESTAMP WITHOUT TIME ZONE,
    status VARCHAR(20) NOT NULL DEFAULT 'ASSIGNED',
    CONSTRAINT fk_room_assignments_student
        FOREIGN KEY (student_id) REFERENCES public.students (id),
    CONSTRAINT fk_room_assignments_room
        FOREIGN KEY (room_id) REFERENCES public.rooms (id),
    CONSTRAINT fk_room_assignments_assigned_by
        FOREIGN KEY (assigned_by) REFERENCES public.users (id)
);

-- Keep reruns compatible with a room_assignments table created by an earlier
-- feature revision before the main RoomAssignment shape was adopted.
ALTER TABLE public.room_assignments
    ADD COLUMN IF NOT EXISTS student_id BIGINT,
    ADD COLUMN IF NOT EXISTS contract_id BIGINT,
    ADD COLUMN IF NOT EXISTS assigned_by BIGINT,
    ADD COLUMN IF NOT EXISTS check_in_at TIMESTAMP WITHOUT TIME ZONE,
    ADD COLUMN IF NOT EXISTS check_out_at TIMESTAMP WITHOUT TIME ZONE;

CREATE INDEX IF NOT EXISTS idx_dorm_applications_student
    ON public.dorm_applications (student_id);
CREATE INDEX IF NOT EXISTS idx_dorm_applications_status
    ON public.dorm_applications (status);
CREATE INDEX IF NOT EXISTS idx_room_assignments_room_status
    ON public.room_assignments (room_id, status);
CREATE INDEX IF NOT EXISTS idx_room_assignments_student_status
    ON public.room_assignments (student_id, status);
CREATE INDEX IF NOT EXISTS idx_room_assignments_contract
    ON public.room_assignments (contract_id);

COMMIT;
